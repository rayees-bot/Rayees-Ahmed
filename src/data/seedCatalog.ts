export async function ensureFirestoreSeeded(userUid?: string): Promise<void> {
  if (!userUid) return;
  try {
    const [medSnap, pharmSnap, partnerSnap] = await Promise.all([
      getDoc(doc(db, 'medicines', 'med_dolo_650')),
      getDoc(doc(db, 'pharmacies', 'pharm_medihub_central')),
      getDoc(doc(db, 'deliveryPartners', 'partner_arjun_01')),
    ]);

    if (medSnap.exists() && pharmSnap.exists() && partnerSnap.exists()) {
      return;
    }

    const batch = writeBatch(db);
    if (!pharmSnap.exists()) {
      for (const p of buildSeedPharmacies(userUid)) {
        batch.set(doc(db, 'pharmacies', p.id), p);
      }
    }
    if (!partnerSnap.exists()) {
      for (const dp of buildSeedDeliveryPartners(userUid)) {
        batch.set(doc(db, 'deliveryPartners', dp.id), dp);
      }
    }
    if (!medSnap.exists()) {
      for (const m of buildSeedMedicines(userUid)) {
        batch.set(doc(db, 'medicines', m.id), m);
      }
    }
    await batch.commit();
  } catch (error) {
    handleFirestoreError(error, OperationType.WRITE, 'seed_catalog');
  }
}
